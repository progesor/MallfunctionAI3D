import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateApiProduction, prepareApiProduction, assertInstalledNodes } from '../lib/api-workflow.ts';
import { DEFAULT_OPTIONS } from '../lib/workflow.ts';
const root=path.dirname(fileURLToPath(import.meta.url));
const raw=JSON.parse(fs.readFileSync(path.resolve(root,'../../../workflows/PLAYBOX_FoxPlush_pixal3d_api_v01.json'),'utf8'));
const stats=validateApiProduction(raw);
assert.equal(stats.mode,'pixal3d');
assert.ok(stats.nodeCount>50);
assert.ok(stats.outputNodes.includes('322'));
assert.ok(raw['322'].inputs.viewport_state.camera_info);
const before=JSON.stringify(raw);
const ready=prepareApiProduction(raw,{...DEFAULT_OPTIONS,triangles:5000,textureSize:2048,seed:118},'fox_uploaded.png','trellis2');
assert.equal(JSON.stringify(raw),before,'immutable source');
assert.equal(ready['316'].inputs.value,true);
assert.equal(ready['322'].inputs.filename_prefix,'3d/Mallfunction/Studio_trellis2');
assert.equal(ready['122'].inputs.image,'fox_uploaded.png');
assert.equal(ready['186'].inputs.target_face_count,5000);
assert.equal(ready['288'].inputs.value,2048);
assert.deepEqual(ready['147'].inputs.texture_size,['288',0]);
assert.deepEqual(ready['196'].inputs.resolution,['288',0]);
assert.equal(ready['322'].inputs.viewport_state.camera_info.cameraType,'perspective');
assert.equal(ready['3'].inputs.seed,118);
assert.ok(!ready['323'],'unrelated Preview3D output should not execute');
assert.ok(!ready['262'],'unrelated UV preview should not execute');
assert.ok(ready['303'],'mask pass-through required for crop remains');
assert.ok(ready['322'],'Save3D output remains');
const missingSave=structuredClone(raw);delete missingSave['322'];
assert.throws(()=>validateApiProduction(missingSave),/Save3DAdvanced/);
const maskOnly=structuredClone(raw);maskOnly['322'].inputs.model_3d=['303',0];
assert.throws(()=>validateApiProduction(maskOnly),/Save3DAdvanced/);
const viewportBad=structuredClone(raw);viewportBad['322'].inputs.viewport_state='';
assert.throws(()=>validateApiProduction(viewportBad),/viewport_state/);
const broken=structuredClone(raw);broken['285'].inputs.mesh=['999999',0];
assert.throws(()=>validateApiProduction(broken),/999999/);
const info=Object.fromEntries([...new Set(Object.values(raw).map(n=>n.class_type))].map(x=>[x,{}]));
assertInstalledNodes(raw,info);
assert.throws(()=>assertInstalledNodes(raw,{Save3DAdvanced:{}}),/eksik/);
console.log('PASS: API-exported Pixal3D full GLB chain, connected UV/texture, immutable presets, safety checks');
